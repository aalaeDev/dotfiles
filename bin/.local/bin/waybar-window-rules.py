#!/usr/bin/env python3
"""Generate rewrite rules for waybar's hyprland/window module.

The module shows the app icon itself ("icon": true), so for apps whose icon can be
found the title only needs to lose its trailing app name ("x - Visual Studio Code"
becomes "x"). Apps without an icon fall through to the rules in modules.jsonc
(Arch logo + full title); waybar merges both rule sets.

Waybar can't tell a rewrite rule whether it found an icon, so this mirrors its lookup
(AAppIconLabel): the first .desktop file, user dir before system dirs, whose file name
ends with the window class (case-insensitive), and that file's Icon= key. StartupWMClass
is not consulted. Run at waybar start; output lives in ~/.cache.
"""

import configparser
import json
import os
import re
from pathlib import Path

OUT = Path.home() / ".cache/waybar/window-rules.jsonc"
SEP = "\u001f"  # between {class} and {title} in the module's format


def data_dirs() -> list[Path]:
    home = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local/share")
    system = os.environ.get("XDG_DATA_DIRS") or "/usr/local/share:/usr/share"
    return [Path(d) for d in [home, *system.split(":")] if d]


def regex_escape(text: str) -> str:
    # Only ECMAScript metacharacters; std::regex rejects escapes it doesn't know
    return "".join("\\" + c if c in r".^$|?*+()[]{}\/" else c for c in text)


def class_candidates(stem: str) -> list[str]:
    """Classes waybar would match to this file: the name and its tails after "." or "-"
    (it accepts any suffix; these are the ones real window classes use)."""
    stem = stem.lower()
    return [stem] + [stem[m.end():] for m in re.finditer(r"[.-]", stem) if stem[m.end():]]


def apps() -> dict[str, str]:
    """Window class (lower-case) -> app name, for classes whose desktop file has an icon."""
    first: dict[str, configparser.SectionProxy | None] = {}
    for data in data_dirs():
        for desktop in sorted((data / "applications").glob("*.desktop")):
            parser = configparser.ConfigParser(interpolation=None, strict=False)
            try:
                parser.read(desktop, encoding="utf-8")
                entry = parser["Desktop Entry"]
            except (configparser.Error, KeyError, UnicodeDecodeError):
                entry = None
            for cls in class_candidates(desktop.stem):
                first.setdefault(cls, entry)  # waybar stops at the first matching file
    return {cls: e.get("Name", "") for cls, e in first.items() if e is not None and e.get("Icon")}


def main() -> None:
    rules = {}
    by_name: dict[str, list[str]] = {}
    for cls, name in apps().items():
        by_name.setdefault(name, []).append(cls)

    # Icon found: drop the trailing " - <App Name>" (any dash), keep the rest of the title
    for name, classes in by_name.items():
        alts = "|".join(sorted(regex_escape(c) for c in classes))
        suffix = f"(?: [-–—] {regex_escape(name)})?" if name else ""
        rules[f"^(?:{alts}){SEP}(.*?){suffix}$"] = "$1"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = "// Generated by waybar-window-rules.py at waybar start; edits are overwritten\n"
    OUT.write_text(header + json.dumps({"hyprland/window": {"rewrite": rules}}, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
